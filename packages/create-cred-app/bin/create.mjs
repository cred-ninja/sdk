#!/usr/bin/env node

/**
 * create-cred-app — Scaffold a self-hosted Cred server
 *
 * Usage:
 *   npx @credninja/create-app my-cred-server
 *   npx @credninja/create-app .              # scaffold in current directory
 */

import { mkdirSync, writeFileSync, copyFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { generateKeyPairSync, randomBytes } from 'node:crypto';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const TEMPLATE_DIR = join(__dirname, '..', 'template');

const name = process.argv[2];

if (!name || name === '--help' || name === '-h') {
  console.log(`
  \x1b[1mcreate-cred-app\x1b[0m — Scaffold a self-hosted Cred server

  \x1b[36mUsage:\x1b[0m
    npx @credninja/create-app <directory>
    npx @credninja/create-app my-server
    npx @credninja/create-app .

  \x1b[1mWhat you get:\x1b[0m
    • Express server powered by @credninja/server
    • SQLite vault (zero-config, no external DB)
    • Admin UI at /connect for managing OAuth providers
    • Pre-configured for Google, GitHub, Slack
    • Docker + Caddy deployment option
  `);
  process.exit(name ? 0 : 1);
}

const targetDir = resolve(process.cwd(), name);
const skipInstall = process.env.CREATE_CRED_APP_SKIP_INSTALL === '1';

console.log();
console.log(`  \x1b[1m🦀 create-cred-app\x1b[0m`);
console.log();

// Create directory
if (name !== '.') {
  if (existsSync(targetDir)) {
    console.error(`  \x1b[31m✗\x1b[0m Directory "${name}" already exists.`);
    process.exit(1);
  }
  mkdirSync(targetDir, { recursive: true });
  console.log(`  \x1b[32m✓\x1b[0m Created ${name}/`);
}

// Copy template files recursively
const BASE58 = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';

function base58(bytes) {
  let value = BigInt(`0x${Buffer.from(bytes).toString('hex')}`);
  let out = '';
  while (value > 0n) {
    out = BASE58[Number(value % 58n)] + out;
    value /= 58n;
  }
  for (const byte of bytes) {
    if (byte !== 0) break;
    out = `1${out}`;
  }
  return out;
}

/** An Ed25519 did:key and its private key, the form @credninja/sdk imports. */
function generateAgentIdentity() {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const x = Buffer.from(publicKey.export({ format: 'jwk' }).x, 'base64url');
  const d = Buffer.from(privateKey.export({ format: 'jwk' }).d, 'base64url');
  return { did: `did:key:z${base58(Buffer.concat([Buffer.from([0xed, 0x01]), x]))}`, privateKeyHex: d.toString('hex') };
}

function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const entry of readdirSync(src)) {
    const srcPath = join(src, entry);
    const outputName = entry === 'gitignore' ? '.gitignore' : entry;
    const destPath = join(dest, outputName);
    if (statSync(srcPath).isDirectory()) {
      copyDir(srcPath, destPath);
    } else {
      copyFileSync(srcPath, destPath);
      console.log(`  \x1b[32m✓\x1b[0m ${destPath.replace(targetDir + '/', '')}`);
    }
  }
}

copyDir(TEMPLATE_DIR, targetDir);

// Generate .env with random passphrase and tokens
const passphrase = randomBytes(32).toString('base64url');
const adminToken = 'cred_admin_' + randomBytes(16).toString('hex');
const agentToken = 'cred_at_' + randomBytes(16).toString('hex');

// The app's first agent. Its private key goes in agent.env, not .env: the
// server never needs it, and on two machines it stays with the agent.
const agent = generateAgentIdentity();

const envContent = `# Generated by create-cred-app
# ⚠️  Keep this file secure — it contains your encryption passphrase

# Vault encryption passphrase (DO NOT LOSE — encrypts all stored tokens)
VAULT_PASSPHRASE=${passphrase}

# Server config
PORT=3456
HOST=127.0.0.1
REDIRECT_BASE_URI=http://localhost:3456
VAULT_STORAGE=sqlite
VAULT_PATH=./data/vault.sqlite
TOFU_STORAGE=sqlite
TOFU_PATH=./data/tofu.sqlite

# Admin token (for management APIs)
ADMIN_TOKEN=${adminToken}

# Agent token (agents use this to request credentials)
AGENT_TOKEN=${agentToken}

# Every request names the user it acts for (user_id). Set to true only when
# this server holds one person's accounts: a request without user_id then acts
# on the shared user "default".
SINGLE_USER_MODE=false

# ─── Provider OAuth Credentials ───────────────────────────
# Uncomment and fill in the providers you want to use.
# Get credentials from each provider's developer console.

# Google: https://console.cloud.google.com/apis/credentials
# GOOGLE_CLIENT_ID=
# GOOGLE_CLIENT_SECRET=
# GOOGLE_DEFAULT_SCOPES=openid,email,profile

# GitHub: https://github.com/settings/developers
# GITHUB_CLIENT_ID=
# GITHUB_CLIENT_SECRET=
# GITHUB_DEFAULT_SCOPES=repo,user

# Slack: https://api.slack.com/apps
# SLACK_CLIENT_ID=
# SLACK_CLIENT_SECRET=
# SLACK_DEFAULT_SCOPES=chat:write,channels:read
`;

writeFileSync(join(targetDir, '.env'), envContent, { mode: 0o600 });
console.log(`  \x1b[32m✓\x1b[0m .env (generated with random passphrase + tokens)`);

writeFileSync(join(targetDir, 'agent.env'), `# Generated by create-cred-app: what your agent needs, and nothing the server does.
# Keep this file secure: the private key proves this agent's identity.
CRED_BASE_URL=http://localhost:3456
CRED_AGENT_TOKEN=${agentToken}
CRED_AGENT_DID=${agent.did}
CRED_AGENT_PRIVATE_KEY_HEX=${agent.privateKeyHex}
`, { mode: 0o600 });
console.log(`  \x1b[32m✓\x1b[0m agent.env (a new agent identity, for your agent)`);

// Install dependencies
console.log();
if (skipInstall) {
  console.log(`  \x1b[33m⚠\x1b[0m Skipped npm install because CREATE_CRED_APP_SKIP_INSTALL=1`);
} else {
  console.log(`  \x1b[36mInstalling dependencies...\x1b[0m`);
  try {
    execSync('npm install', { cwd: targetDir, stdio: 'pipe' });
    console.log(`  \x1b[32m✓\x1b[0m Dependencies installed`);
  } catch (e) {
    console.log(`  \x1b[33m⚠\x1b[0m npm install failed — run it manually`);
  }
}

// Done
console.log();
console.log(`  \x1b[1m\x1b[32m✓ Done!\x1b[0m`);
console.log();
console.log(`  \x1b[1mNext steps:\x1b[0m`);
if (name !== '.') {
  console.log(`  \x1b[36mcd ${name}\x1b[0m`);
}
console.log(`  \x1b[36mnpm start\x1b[0m`);
console.log();
console.log(`  \x1b[1mThen:\x1b[0m`);
console.log(`  1. Add OAuth credentials to \x1b[36m.env\x1b[0m and restart`);
console.log(`  2. Open \x1b[36mhttp://localhost:3456/admin/login\x1b[0m, sign in with ADMIN_TOKEN from .env, and connect a provider for a user`);
console.log(`  3. Grant your agent what it may do: \x1b[36mnpm run grant -- github github.read\x1b[0m`);
console.log(`  4. Give your agent \x1b[36magent.env\x1b[0m`);
console.log();
console.log(`  \x1b[90mDocs: https://cred.ninja/docs\x1b[0m`);
console.log();
